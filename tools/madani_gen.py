    u=f'https://api.quran.com/api/v4/verses/by_key/{s}:{a}?words=true&word_fields=text_uthmani,transliteration&language={lang}'
    for _ in range(4):
        try:
            d=json.load(urllib.request.urlopen(urllib.request.Request(u,headers={'User-Agent':'Mozilla/5.0'}),timeout=30));json.dump(d,open(f,'w'));return d
        except Exception as e: err=e
    raise err
