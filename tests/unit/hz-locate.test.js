import {test,expect} from 'vitest';
import {locate} from '../../src/hz-locate.js';
import {Tracker} from '../../src/recite-live.js';
import {norm} from '../../src/recite-core.js';
import fs from 'node:fs';
const ar=JSON.parse(fs.readFileSync('public/offline/s/ar/1.json'));
const flat=[];ar.forEach((x,a)=>x.split(/\s+/).map(norm).filter(Boolean).forEach((n,k)=>flat.push({n,a:a+1,k})));
const W=flat.map(x=>x.n),starts=flat.map((x,i)=>x.k===0?i:-1).filter(i=>i>=0),ay=i=>flat[i].a;
const H=s=>s.split(' ').map(norm).map((w,i)=>({w,t0:0.1+i*0.4,t1:0.4+i*0.4}));
test('locates a reciter who starts at a later ayah',()=>{const T=new Tracker(W);const h=H('إياك نعبد وإياك نستعين اهدنا الصراط المستقيم');const i=locate(T,W,starts,{},h,3,undefined,ay);expect(ay(i)).toBe(5)});
test('unrelated words and too few words never locate',()=>{const T=new Tracker(W);expect(locate(T,W,starts,{},H('كتاب قلم شجر بيت سماء نهر'),3,undefined,ay)).toBe(-1);expect(locate(T,W,starts,{},H('إياك نعبد'),3,undefined,ay)).toBe(-1)});
test('a verified tracker is never moved',()=>{const T=new Tracker(W);T.verified=true;expect(locate(T,W,starts,{},H('إياك نعبد وإياك نستعين اهدنا'),3,undefined,ay)).toBe(-1)});
